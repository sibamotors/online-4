type LangContextType = {
  lang: "fa" | "en";
  setLang: (l: "fa" | "en") => void;
  t: (key: string) => string;
};

const LanguageContext = createContext<LangContextType>({
  lang: "fa",
  setLang: () => {},
  t: (k) => translations.fa[k as keyof typeof translations.fa] || k,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<"fa" | "en">("fa");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("sibamotor-lang") as "fa" | "en";
      if (saved === "en" || saved === "fa") {
        setLangState(saved);
        document.documentElement.setAttribute("lang", saved);
        document.documentElement.setAttribute("dir", saved === "fa" ? "rtl" : "ltr");
      }
    } catch {
      // ignore
    }
  }, []);

  const setLang = (l: "fa" | "en") => {
    setLangState(l);
    try {
      localStorage.setItem("sibamotor-lang", l);
      document.documentElement.setAttribute("lang", l);
      document.documentElement.setAttribute("dir", l === "fa" ? "rtl" : "ltr");
    } catch {
      // ignore
    }
  };

  const t = (key: string) => {
    if (lang === "en" && guideEnglish[key]) return guideEnglish[key];
    return translations[lang]?.[key as keyof typeof translations["fa"]] || translations.fa[key as keyof typeof translations["fa"]] || key;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useTranslation() {
  return useContext(LanguageContext);
}
